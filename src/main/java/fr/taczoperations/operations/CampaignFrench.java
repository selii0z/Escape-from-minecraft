    static String title(String source){
        String key=source.toLowerCase(Locale.ROOT).replaceAll("[’']", "").replaceAll("[^\\p{L}\\p{N}]+"," ").trim();
        var result=TITLES.get(key);
        if(result!=null)return result;
        // Handle series not present in the tested snapshot without altering their identity.
        var series=java.util.regex.Pattern.compile("^(the punisher|the tarkov shooter|farming|signal|spa tour|chemical|broadcast|sanitary standards|health care privacy|sew it good|the blood of war|hell on earth|fair price|operation aquarius|friend from the west|beyond the red meat|textile|drip out|shipping delay|sensory analysis|easy money|balancing|create a distraction|professional fitness|against the conscience) part (\\d+)(.*)$").matcher(key);
        if(series.matches()){
            String base=switch(series.group(1)){
                case "the punisher"->"Le justicier";case "the tarkov shooter"->"Le tireur de Tarkov";
                case "farming"->"Culture";case "signal"->"Signal";case "spa tour"->"Circuit thermal";
                case "chemical"->"Chimie";case "broadcast"->"Diffusion";case "sanitary standards"->"Normes sanitaires";
                case "health care privacy"->"Secret médical";case "sew it good"->"Couds-le bien";
                case "the blood of war"->"Le sang de la guerre";case "hell on earth"->"L'enfer sur terre";
                case "fair price"->"Juste prix";case "operation aquarius"->"Opération Verseau";
                case "friend from the west"->"Un ami de l'Ouest";case "beyond the red meat"->"Au-delà de la viande rouge";
                case "textile"->"Textile";case "drip out"->"À la mode";case "shipping delay"->"Retard de livraison";
                case "sensory analysis"->"Analyse sensorielle";case "easy money"->"Argent facile";case "balancing"->"Équilibrage";
                case "create a distraction"->"Créer une diversion";case "professional fitness"->"Aptitude professionnelle";
                default->"Contre sa conscience";
            };
            String tail=series.group(3).trim();
            if(tail.equals("pve zone"))tail="(JcE)";
            else if(tail.equals("bear")||tail.equals("usec"))tail="("+tail.toUpperCase(Locale.ROOT)+")";
            return base+" – Partie "+series.group(2)+(tail.isEmpty()?"":" "+tail);
        }
        return source;
    }
